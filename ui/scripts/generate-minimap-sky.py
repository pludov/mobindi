#!/usr/bin/env python3
"""Generate the minimap catalog from the pinned HYG and Stellarium inputs."""

import argparse
import csv
import gzip
import hashlib
import json
import math
from pathlib import Path

HYG_SHA256 = "8e3ff9e67445e558a759b117910850cff1b1d4d492f45f715c2ee2db3d869bac"
LINES_SHA256 = "1f2f5ffd6c9e25a7d0dcfdbf1f756e2db03dd3b8ed4ec016a2839b09f6b0fe1e"
OUTPUT = Path(__file__).resolve().parents[1] / "src/MiniMap/skyData.ts"


def verify(path, expected):
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != expected:
        raise ValueError(f"{path}: SHA-256 {digest} does not match {expected}")


def generate(hyg, lines):
    verify(hyg, HYG_SHA256)
    verify(lines, LINES_SHA256)
    source = json.loads(lines.read_text(encoding="utf-8"))
    segments = []
    for constellation in source["constellations"]:
        for line in constellation.get("lines", []):
            segments.extend(zip(line, line[1:]))
    endpoints = {star for segment in segments for star in segment}
    stars = {}
    with gzip.open(hyg, "rt", encoding="utf-8", newline="") as file:
        for row in csv.DictReader(file):
            if not row["hip"] or not row["mag"]:
                continue
            hip, mag = int(row["hip"]), float(row["mag"])
            if hip not in endpoints and mag > 4:
                continue
            ra, dec = float(row["ra"]) * 15, float(row["dec"])
            if not all(math.isfinite(value) for value in (ra, dec, mag)) or not (0 <= ra < 360 and -90 <= dec <= 90):
                raise ValueError(f"Invalid HYG star {hip}")
            entry = (hip, round(ra, 6), round(dec, 6), round(mag, 2))
            if hip not in stars or mag < stars[hip][3]:
                stars[hip] = entry
    missing = endpoints - stars.keys()
    if missing:
        raise ValueError(f"Missing constellation endpoints: {sorted(missing)}")
    ordered = [stars[hip] for hip in sorted(stars)]
    index = {star[0]: i for i, star in enumerate(ordered)}
    indexed = [(index[a], index[b]) for a, b in segments]
    if len(ordered) > 1000 or len(indexed) > 1500:
        raise ValueError("Sky data exceeds the intended size limits")
    star_rows = "\n".join(f"    [{a}, {b}, {c}, {d}]," for a, b, c, d in ordered)
    line_rows = "\n".join(f"    [{a}, {b}]," for a, b in indexed)
    return (
        "// Generated by ui/scripts/generate-minimap-sky.py; see MiniMap/README.md.\n"
        "// HYG and Stellarium modern sky culture data: CC BY-SA 4.0.\n"
        "export const stars: ReadonlyArray<readonly [number, number, number, number]> = [\n"
        f"{star_rows}\n];\n\n"
        "export const segments: ReadonlyArray<readonly [number, number]> = [\n"
        f"{line_rows}\n];\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("hyg", type=Path, help="Pinned hygdata_v40.csv.gz")
    parser.add_argument("lines", type=Path, help="Pinned Stellarium modern index.json")
    parser.add_argument("--check", action="store_true", help="Check the committed output instead of writing it")
    args = parser.parse_args()
    content = generate(args.hyg, args.lines)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit(f"{OUTPUT} differs from regenerated output")
        print(f"{OUTPUT} matches regenerated output")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
